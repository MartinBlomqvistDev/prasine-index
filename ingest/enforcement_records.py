"""Verified enforcement records on environmental claims.

Every record was checked on 2026-11-05 against the authority's own page and
then re-checked independently: reference, decision date, party and outcome as
the authority states them, and a quote copied verbatim from that page. Records
that could not be traced to an official page were removed. Update this file
only with records checked the same way.
"""

from __future__ import annotations

from dataclasses import dataclass

__all__ = ["RULINGS", "Ruling"]


@dataclass(frozen=True, slots=True)
class Ruling:
    """A single enforcement decision, commitment or case on environmental claims.

    Attributes:
        companies: Name variants used to match the record to a company.
        party_as_named: The party exactly as the authority names it.
        authority: Short identifier of the authority or body.
        country: Country of the authority.
        decision_date: Date of the decision or publication, YYYY-MM-DD.
        case_reference: The reference exactly as the authority writes it.
        ruling_type: BANNED, CONFIRMED_MISLEADING, FINED, COMMITMENTS, WARNING,
            INVESTIGATION, NOT_UPHELD or ANNULLED.
        claim_type: Category of the claim the record concerns.
        description: Neutral summary for human readers; never shown as a finding.
        quote: Verbatim quotation from the official page.
        source_url: The official page.
        archive_url: A Wayback Machine capture of the page, if one exists.
        outcome: The outcome in the authority's own terms, where the general
            wording for ruling_type would say less than the authority does.
        body: What kind of body the authority is, where its name does not say,
            such as an advertising self-regulator.
    """

    companies: tuple[str, ...]
    party_as_named: str
    authority: str
    country: str
    decision_date: str
    case_reference: str
    ruling_type: str
    claim_type: str
    description: str
    quote: str
    source_url: str
    archive_url: str | None
    outcome: str = ""
    body: str = ""


